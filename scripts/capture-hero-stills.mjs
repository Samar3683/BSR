import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { parseArgs } from "node:util";

import { chromium } from "@playwright/test";

const root = path.resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);
const sharp = require(
  require.resolve("sharp", { paths: [path.dirname(require.resolve("next/package.json"))] }),
);

const { values: args } = parseArgs({
  options: {
    url: { type: "string", default: "http://localhost:3100" },
    only: { type: "string" },
  },
});

/** Mirrors HERO_CHECKPOINTS (src/experiences/home/config/hero-states.ts). */
const STILLS = [
  { id: "s1", checkpoint: "opening", progress: 0.04 },
  { id: "s2", checkpoint: "hold", progress: 0.39 },
  { id: "s3", checkpoint: "road", progress: 0.77 },
  { id: "s4", checkpoint: "route", progress: 0.97 },
];
const LAYOUTS = [
  { name: "wide", width: 2560, height: 1440 },
  { name: "compact", width: 1080, height: 1920 },
];
const CLIPS = [
  { id: "a", from: 0.04, to: 0.39, seconds: 4.5 },
  { id: "b", from: 0.39, to: 0.97, seconds: 7 },
];
const FPS = 30;
/** HERO_RIG.cruiseSpeed (m/s). */
const CRUISE = 21;
const HIDE_COPY = `
  [data-hero] > div:first-child, [data-hero] > p, [data-hero] [class*="scrim"],
  body > header, [data-site-header] { visibility: hidden !important; }
`;
const STILL_DIR = path.join(root, "public/assets/images/fallback/hero");
const CLIP_DIR = path.join(root, "public/assets/video/hero");
const MANIFEST = path.join(root, "src/experiences/home/config/hero-captures.ts");

/**
 * Content-addressed names: `<stem>.<hash>.<ext>`. A re-capture never reuses a URL, so no
 * browser, CDN or image-optimiser cache can serve the previous frame. Older versions of
 * the same stem are removed.
 */
function settle(file) {
  const dir = path.dirname(file);
  const ext = path.extname(file);
  const stem = path.basename(file, ext);
  const hash = createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 10);
  for (const old of readdirSync(dir)) {
    if (old.startsWith(`${stem}.`) && old.endsWith(ext) && old !== path.basename(file)) {
      rmSync(path.join(dir, old));
    }
  }
  const named = `${stem}.${hash}${ext}`;
  renameSync(file, path.join(dir, named));
  return named;
}

/** The generated manifest (read by hero-assets.ts); a partial run keeps the other half. */
const manifest = existsSync(MANIFEST)
  ? JSON.parse(
      readFileSync(MANIFEST, "utf8")
        .replace(/^[^=]*=\s*/s, "")
        .replace(/\s*as const;\s*$/, ""),
    )
  : { stills: {}, clips: {} };
function writeManifest() {
  writeFileSync(
    MANIFEST,
    `/** GENERATED by scripts/capture-hero-stills.mjs — do not edit. File names carry a content hash. */\n` +
      `export const HERO_CAPTURES = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  );
}

async function openHero(width, height) {
  const browser = await chromium.launch({ args: ["--ignore-gpu-blocklist", "--enable-gpu"] });
  const page = await browser.newPage({ viewport: { width, height }, deviceScaleFactor: 1 });
  await page.goto(`${args.url}/?hero-path=realtime&hero-tier=high`);
  await page.waitForFunction(
    () => window.__BSR_HERO__?.realtime === "active" && window.__BSR_HERO__.runtime?.hasRoad,
    null,
    { timeout: 120_000 },
  );
  await page.waitForTimeout(3000); // road warm-ups
  await page.addStyleTag({ content: HIDE_COPY });
  await page.evaluate(() => {
    const runtime = window.__BSR_HERO__.runtime;
    if (!runtime.frozen) runtime.toggleFrozen();
  });
  return { browser, page };
}

/** Story state for progress p, frozen; optional road flow / wheel travel override. */
async function pose(page, p, flow) {
  await page.evaluate((p) => {
    const s = document.querySelector("[data-hero]");
    window.scrollTo({ top: s.offsetTop + p * (s.offsetHeight - innerHeight), behavior: "instant" });
  }, p);
  await page.waitForFunction((p) => Math.abs(window.__BSR_HERO__.progress.displayed - p) < 1e-3, p);
  await page.evaluate((flow) => {
    const runtime = window.__BSR_HERO__.runtime;
    runtime.snapToProgress();
    if (flow) {
      runtime.roadOffset = flow.roadOffset;
      runtime.wheelTravel = flow.wheelTravel;
    } else runtime.wheelTravel = runtime.dock.distance; // wheels turn with the departure
    runtime.markDirty();
  }, flow);
  // Two rendered frames: the snap's one-off work, then a settled frame.
  await page.evaluate(
    () => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))),
  );
  await page.waitForTimeout(60);
}

async function captureStills() {
  mkdirSync(STILL_DIR, { recursive: true });
  for (const layout of LAYOUTS) {
    const { browser, page } = await openHero(layout.width, layout.height);
    for (const still of STILLS) {
      await pose(page, still.progress);
      await page.waitForTimeout(600);
      const png = await page.screenshot();
      const file = path.join(STILL_DIR, `hero-${still.id}-${still.checkpoint}-${layout.name}.webp`);
      await sharp(png).webp({ quality: 90, effort: 6, smartSubsample: true }).toFile(file);
      const named = settle(file);
      (manifest.stills[still.id.toUpperCase()] ??= {})[layout.name] = named;
      console.log("still", named);
    }
    await browser.close();
  }
}

const easeInOut = (t) => t * t * (3 - 2 * t);
const ROAD_FLOW_START = 0.615; // HERO_MARKS.wipeEnd: the road world runs from here on

async function captureClips() {
  mkdirSync(CLIP_DIR, { recursive: true });
  const { browser, page } = await openHero(720, 1280);
  for (const clip of CLIPS) {
    const frames = Math.round(clip.seconds * FPS);
    const dir = mkdtempSync(path.join(tmpdir(), `hero-clip-${clip.id}-`));
    let roadOffset = 0;
    for (let i = 0; i < frames; i++) {
      const p = clip.from + (clip.to - clip.from) * easeInOut(i / (frames - 1));
      if (p >= ROAD_FLOW_START) roadOffset += CRUISE / FPS;
      // Dock: wheels follow the departure distance (snapped); road: wipe distance + flow.
      const flow = p >= ROAD_FLOW_START ? { roadOffset, wheelTravel: 22 + roadOffset } : null;
      await pose(page, p, flow);
      await page.screenshot({ path: path.join(dir, `f${String(i).padStart(4, "0")}.png`) });
    }
    const input = ["-y", "-framerate", String(FPS), "-i", path.join(dir, "f%04d.png")];
    const out = (codec) => path.join(CLIP_DIR, `hero-clip-${clip.id}.${codec}.mp4`);
    execFileSync(
      "ffmpeg",
      [
        ...input,
        "-c:v",
        "libsvtav1",
        "-preset",
        "5",
        "-crf",
        "46",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        "-an",
        out("av1"),
      ],
      { stdio: "ignore" },
    );
    execFileSync(
      "ffmpeg",
      [
        ...input,
        "-c:v",
        "libx264",
        "-preset",
        "veryslow",
        "-crf",
        "29",
        "-pix_fmt",
        "yuv420p",
        "-profile:v",
        "high",
        "-movflags",
        "+faststart",
        "-an",
        out("h264"),
      ],
      { stdio: "ignore" },
    );
    rmSync(dir, { recursive: true, force: true });
    manifest.clips[clip.id.toUpperCase()] = { av1: settle(out("av1")), h264: settle(out("h264")) };
    console.log("clip", clip.id, `${frames} frames`);
  }
  await browser.close();
}

if (args.only !== "clips") await captureStills();
if (args.only !== "stills") await captureClips();
writeManifest();
console.log("manifest", path.relative(root, MANIFEST));
