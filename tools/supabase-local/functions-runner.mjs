// Edge-functions runner: one Deno process per supabase/functions/<name>/index.ts. Node built-ins only.
//
//   node functions-runner.mjs [--functions-dir <dir>]
//
// Directories starting with "_" or "." are skipped (shared code, like the Supabase CLI).
// Each function gets its own port (54340, 54341, ...) through a generated wrapper that
// rebinds Deno.serve (and std/http's Deno.listen on :8000) to that port, so functions written
// for the edge runtime (`Deno.serve(handler)`) run unchanged. The directory is rescanned every
// second: new functions start, deleted ones stop, `deno run --watch` reloads on edits.
// State for the gateway is written to .supabase-local/run/functions.json.
import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parseEnv } from "node:util";

import {
  API_URL,
  DB_URL,
  EXE,
  P,
  PORTS,
  ensureDir,
  loadKeys,
  readFunctionsConfig,
  tcpCheck,
  writeJson,
} from "./lib.mjs";

function argValue(name) {
  const i = process.argv.indexOf(name);
  if (i >= 0) return process.argv[i + 1];
  const eq = process.argv.find((a) => a.startsWith(`${name}=`));
  return eq ? eq.slice(name.length + 1) : undefined;
}

const FUNCTIONS_DIR = path.resolve(
  argValue("--functions-dir") || process.env.SUPABASE_LOCAL_FUNCTIONS_DIR || P.functionsDir,
);
const WRAPPER_DIR = ensureDir(path.join(P.run, "functions"));
const keys = loadKeys();
const fns = new Map(); // name -> { port, child, status, verifyJwt, restartAt, entry }
let lastWritten = "";

const BASE_ENV_KEYS = [
  "SystemRoot",
  "SystemDrive",
  "windir",
  "TEMP",
  "TMP",
  "USERPROFILE",
  "LOCALAPPDATA",
  "APPDATA",
  "PATH",
  "HTTP_PROXY",
  "HTTPS_PROXY",
  "NO_PROXY",
  "DENO_CERT",
];

function baseEnv() {
  const env = {};
  for (const [k, v] of Object.entries(process.env)) {
    if (BASE_ENV_KEYS.some((b) => b.toUpperCase() === k.toUpperCase())) env[k] = v;
  }
  return env;
}

function userSecrets() {
  // Like `supabase functions serve`: supabase/functions/.env provides function secrets.
  const file = path.join(FUNCTIONS_DIR, ".env");
  try {
    return parseEnv(fs.readFileSync(file, "utf8"));
  } catch {
    return {};
  }
}

function wrapperSource(entryUrl) {
  return `// generated by tools/supabase-local/functions-runner.mjs — do not edit
const PORT = Number(Deno.env.get("SB_LOCAL_FUNCTION_PORT"));
const HOST = "127.0.0.1";
const originalServe = Deno.serve.bind(Deno);
const originalListen = Deno.listen.bind(Deno);
let bound = false;
function serve(...args: any[]) {
  let options: any = {};
  let handler: any;
  if (typeof args[0] === "function") { handler = args[0]; options = args[1] ?? {}; }
  else if (typeof args[1] === "function") { options = args[0] ?? {}; handler = args[1]; }
  else { options = args[0] ?? {}; handler = options.handler; }
  if (bound) console.warn("[supabase-local] Deno.serve called more than once; only the first server is reachable");
  bound = true;
  const { port: _port, hostname: _hostname, onListen: _onListen, ...rest } = options;
  return originalServe({ ...rest, port: PORT, hostname: HOST, onListen: () => console.log("listening on http://" + HOST + ":" + PORT) }, handler);
}
function listen(options: any) {
  if (options && (options.transport ?? "tcp") === "tcp" && (options.port === undefined || options.port === 8000)) {
    return originalListen({ ...options, port: PORT, hostname: HOST });
  }
  return originalListen(options);
}
Object.defineProperty(Deno, "serve", { value: serve, writable: true, configurable: true });
Object.defineProperty(Deno, "listen", { value: listen, writable: true, configurable: true });
// Minimal EdgeRuntime global (background tasks just run to completion here).
if (!("EdgeRuntime" in globalThis)) {
  (globalThis as any).EdgeRuntime = { waitUntil(p: Promise<unknown>) { Promise.resolve(p).catch((e) => console.error(e)); } };
}
await import(${JSON.stringify(entryUrl)});
`;
}

function denoArgs(name, entry, wrapper) {
  const fnDir = path.dirname(entry);
  const args = ["run", "--watch", "--no-prompt", "--allow-net", "--allow-env", "--allow-read"];
  const config = ["deno.json", "deno.jsonc"]
    .map((f) => path.join(fnDir, f))
    .find((f) => fs.existsSync(f));
  const importMap = path.join(FUNCTIONS_DIR, "import_map.json");
  if (config) args.push("--config", config);
  else {
    args.push("--no-config");
    if (fs.existsSync(importMap)) args.push("--import-map", importMap);
  }
  args.push(wrapper);
  return args;
}

function scan() {
  const found = new Map();
  let entries = [];
  try {
    entries = fs.readdirSync(FUNCTIONS_DIR, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const e of entries) {
    if (!e.isDirectory() || e.name.startsWith("_") || e.name.startsWith(".")) continue;
    const entry = path.join(FUNCTIONS_DIR, e.name, "index.ts");
    if (fs.existsSync(entry)) found.set(e.name, entry);
  }
  return found;
}

async function allocatePort() {
  const used = new Set([...fns.values()].map((f) => f.port));
  for (let port = PORTS.functionsBase; port < PORTS.functionsBase + 200; port++) {
    if (used.has(port)) continue;
    if (!(await tcpCheck(port, "127.0.0.1", 300))) return port;
  }
  throw new Error("no free function port");
}

function start(name, f) {
  const wrapper = path.join(WRAPPER_DIR, `${name}.ts`);
  fs.writeFileSync(wrapper, wrapperSource(pathToFileURL(f.entry).href));
  const env = {
    ...baseEnv(),
    // Site URL of the admin app (cli.mjs passes BSR_SITE_URL / default http://localhost:3100).
    ...(process.env.ADMIN_SITE_URL ? { ADMIN_SITE_URL: process.env.ADMIN_SITE_URL } : {}),
    ...userSecrets(),
    SUPABASE_URL: API_URL,
    SUPABASE_ANON_KEY: keys.anonKey,
    SUPABASE_SERVICE_ROLE_KEY: keys.serviceRoleKey,
    SUPABASE_DB_URL: DB_URL,
    SUPABASE_PUBLISHABLE_KEYS: JSON.stringify({ default: keys.publishableKey }),
    SUPABASE_SECRET_KEYS: JSON.stringify({ default: keys.secretKey }),
    SB_LOCAL_FUNCTION_PORT: String(f.port),
    DENO_DIR: P.denoDir,
    DENO_NO_PACKAGE_JSON: "1",
    DENO_NO_UPDATE_CHECK: "1",
    NO_COLOR: "1",
  };
  const child = spawn(EXE.deno, denoArgs(name, f.entry, wrapper), {
    cwd: path.dirname(f.entry),
    env,
    windowsHide: true,
    stdio: ["ignore", "pipe", "pipe"],
  });
  const prefix = (stream) => {
    let buf = "";
    stream.setEncoding("utf8");
    stream.on("data", (d) => {
      buf += d;
      const lines = buf.split(/\r?\n/);
      buf = lines.pop();
      for (const line of lines) if (line.trim()) console.log(`[${name}] ${line}`);
    });
  };
  prefix(child.stdout);
  prefix(child.stderr);
  child.on("exit", (code) => {
    if (f.child !== child) return;
    console.log(`[${name}] deno exited with code ${code}`);
    f.child = null;
    f.status = "exited";
    f.restartAt = Date.now() + 2000;
  });
  f.child = child;
  f.status = "starting";
  console.log(`[${name}] starting on port ${f.port} (pid ${child.pid})`);
}

function stop(name, f) {
  if (f.child) {
    const child = f.child;
    f.child = null;
    child.kill();
  }
  console.log(`[${name}] stopped`);
}

async function tick() {
  const found = scan();
  const config = readFunctionsConfig();
  for (const [name, f] of fns) {
    if (!found.has(name) || found.get(name) !== f.entry) {
      stop(name, f);
      fns.delete(name);
    }
  }
  for (const [name, entry] of found) {
    let f = fns.get(name);
    if (!f) {
      f = { entry, port: await allocatePort(), child: null, status: "starting", restartAt: 0 };
      fns.set(name, f);
      start(name, f);
    } else if (!f.child && Date.now() >= f.restartAt) {
      start(name, f);
    }
    f.verifyJwt = config[name]?.verify_jwt !== false;
    if (f.child) f.status = (await tcpCheck(f.port, "127.0.0.1", 300)) ? "running" : "starting";
  }
  const state = {
    runnerPid: process.pid,
    functionsDir: FUNCTIONS_DIR,
    functions: Object.fromEntries(
      [...fns].map(([name, f]) => [
        name,
        { port: f.port, pid: f.child?.pid ?? null, status: f.status, verifyJwt: f.verifyJwt },
      ]),
    ),
  };
  const serialized = JSON.stringify(state);
  if (serialized !== lastWritten) {
    for (let i = 0; i < 5; i++) {
      try {
        writeJson(P.functionsState, { ...state, updatedAt: new Date().toISOString() });
        lastWritten = serialized;
        break;
      } catch {
        await new Promise((r) => setTimeout(r, 50));
      }
    }
  }
}

function shutdown() {
  for (const [name, f] of fns) stop(name, f);
  process.exit(0);
}
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);

console.log(
  `functions runner (pid ${process.pid}) serving ${FUNCTIONS_DIR}${fs.existsSync(FUNCTIONS_DIR) ? "" : " (does not exist yet; idling)"}`,
);
for (;;) {
  try {
    await tick();
  } catch (err) {
    console.error(`runner tick failed: ${err.message}`);
  }
  await new Promise((r) => setTimeout(r, 1000));
}
